    private static void scoped(
            Map<String, Rule> rules,
            String mapper,
            String resource,
            String table,
            String column,
            String permission,
            String... methods) {
        for (String method : methods)
            rules.put(
                    "com.adtek.sn.mapper." + mapper + "." + method,
                    Rule.factories(resource, table, column, permission));
    }
