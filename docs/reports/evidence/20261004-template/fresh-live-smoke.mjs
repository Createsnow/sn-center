import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import { resolve } from 'node:path';
const require = createRequire(resolve('frontend/package.json'));
const { chromium, expect } = require('@playwright/test');
const initial = readFileSync('deploy/.secrets/bootstrap-admin-password', 'utf8').trim();
const changed = 'Fresh9!' + randomBytes(16).toString('hex');
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 960 } });
const page = await context.newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.name));
let phase = 'login';
try {
 await page.goto('http://127.0.0.1:15193/login');
 await page.getByLabel('工号', { exact: true }).fill('admin');
 await page.getByLabel('密码', { exact: true }).fill(initial);
 await page.getByRole('button', { name: '登录', exact: true }).click();
 await expect(page.getByRole('heading', { name: '设置你的新密码' })).toBeVisible();
 phase = 'first-password';
 await page.getByLabel('当前密码', { exact: true }).fill(initial);
 await page.getByLabel('新密码', { exact: true }).fill(changed);
 await page.getByLabel('确认新密码', { exact: true }).fill(changed);
 await page.getByRole('button', { name: '修改密码', exact: true }).click();
 await expect(page.getByRole('heading', { name: '登录工作台' })).toBeVisible();
 writeFileSync('deploy/.secrets/proof-admin-current-password', changed, { mode: 0o600 });
 await page.getByLabel('工号', { exact: true }).fill('admin');
 await page.getByLabel('密码', { exact: true }).fill(changed);
 await page.getByRole('button', { name: '登录', exact: true }).click();
 await expect(page.getByRole('heading', { name: '设备台账', exact: true })).toBeVisible();
 phase = 'equipment-create';
 await page.getByRole('button', { name: '新增设备', exact: true }).click();
 let dialog = page.getByRole('dialog');
 await dialog.getByLabel('设备编码', { exact: true }).fill('FRESH-001');
 await dialog.getByLabel('设备名称', { exact: true }).fill('独立空库校验设备');
 await dialog.getByRole('button', { name: '保存', exact: true }).click();
 await expect(dialog).toHaveCount(0);
 const row = page.getByRole('row').filter({ hasText: 'FRESH-001' });
 await expect(row).toContainText('独立空库校验设备');
 phase = 'equipment-update';
 await row.getByRole('button', { name: '编辑设备', exact: true }).click();
 dialog = page.getByRole('dialog');
 await expect(dialog.getByLabel('设备编码', { exact: true })).toBeDisabled();
 await dialog.getByLabel('设备名称', { exact: true }).fill('独立工程验收设备');
 await dialog.getByRole('switch').click();
 await dialog.getByRole('button', { name: '保存', exact: true }).click();
 await expect(dialog).toHaveCount(0);
 await page.reload();
 await expect(row).toContainText('独立工程验收设备');
 await expect(row).toContainText('停用');
 await row.getByRole('button', { name: '设备详情', exact: true }).click();
 dialog = page.getByRole('dialog');
 await expect(dialog.getByText('独立工程验收设备', { exact: true })).toBeVisible();
 await dialog.getByRole('button', { name: '关闭', exact: true }).click();
 await expect(dialog).toHaveCount(0);
 await page.screenshot({ path: 'tools/.runtime/fresh-live-equipment.png', fullPage: true, animations: 'disabled' });
 phase = 'signout';
 await page.getByRole('button', { name: '退出登录', exact: true }).click();
 await expect(page.getByRole('heading', { name: '登录工作台' })).toBeVisible();
 expect(errors).toEqual([]);
 writeFileSync('tools/.runtime/fresh-live-result.json', JSON.stringify({ status: 'PASS', finishedAtUtc: new Date().toISOString(), checks: ['new protected secrets', 'V1-V2 empty database bootstrap', 'first password change', 'login', 'equipment create', 'equipment update immutable code', 'disabled state', 'refresh session and persistence', 'detail', 'signout'], pageErrors: errors }, null, 2));
 console.log('Fresh persistent environment UI passed: first password change, equipment create/update/detail, refresh and signout.');
} catch (e) {
 console.error('Fresh UI failed at stage: ' + phase + '; error type: ' + e.name);
 process.exitCode = 1;
} finally { await browser.close(); }
